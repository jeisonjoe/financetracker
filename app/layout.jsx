"use client";

import { Inter } from "next/font/google";
import localFont from "next/font/local";

import "./globals.css";
import "./styles/styles.scss";
import { Toaster } from "sonner";
import { QueryClient, QueryClientProvider } from "@tanstack/react-query";

const aeonik = localFont({
  variable: "--font-aeonik",
  display: "swap",
  src: [
    { path: "/fonts/AEONIK-THIN.otf", weight: "100", style: "normal" },
    { path: "/fonts/AEONIK-LIGHT.otf", weight: "300", style: "normal" },
    { path: "/fonts/AEONIK-REGULAR.otf", weight: "400", style: "normal" },
    { path: "/fonts/AEONIK-MEDIUM.otf", weight: "600", style: "normal" },
    { path: "/fonts/AEONIK-BOLD.otf", weight: "700", style: "normal" },
    { path: "/fonts/AEONIK-BLACK.otf", weight: "900", style: "normal" },
  ],
});

const inter = Inter({
  variable: "--font-inter",
  subsets: ["latin"],
});

// export const metadata = {
//   title: "Create Next App",
//   description: "Generated by create next app",
// };

const queryClient = new QueryClient();

export default function RootLayout({ children }) {
  return (
    <html lang="en">
      <body
        className={`${aeonik.variable} ${inter.variable} ${aeonik.className}  antialiased`}
      >
        <QueryClientProvider client={queryClient}>
          <Toaster position="top-center" />
          {children}
        </QueryClientProvider>
      </body>
    </html>
  );
}
